import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const generatedBanner = '/* Generated by `npm run build:widgets`. Do not edit directly. */';

// Shared CSS layers, prepended in this order to a widget's authored CSS:
// - `widget-tokens.css`: the `--pw-*` semantic token layer (composed from Homey
//   base tokens), for every widget, so all the widgets read one vocabulary.
// - `widget-frame.css`: the fill-the-frame layout for widgets that sit at a
//   fixed manifest height and never call `Homey.setHeight`.
// - `widget-chart.css`: the summary header + SVG chart furniture shared by the
//   chart widgets.
// - `widget-smart-task-create.css`: the smart-task creation flow, for the
//   widgets that host it.
// The authored source lives in each widget's `src/public/index.css`.
const sharedCssPath = (file) => path.join(rootDir, 'widgets', '_shared', file);
const TOKENS_CSS = 'widget-tokens.css';
const FRAME_CSS = 'widget-frame.css';
const CHART_CSS = 'widget-chart.css';
const CREATE_FLOW_CSS = 'widget-smart-task-create.css';

// Concatenate the shared layers ahead of the widget's authored CSS and emit the
// generated `public/index.css`. Kept as a hand-rolled concat (not an esbuild
// css bundle) so the output stays byte-for-byte the shared files + the authored
// file, trivially reviewable, with no import-resolution or minification step.
const buildWidgetCss = async (widgetDir, sharedCss) => {
  const parts = await Promise.all([
    ...[TOKENS_CSS, ...sharedCss].map((file) => readFile(sharedCssPath(file), 'utf8')),
    readFile(path.join(widgetDir, 'src', 'public', 'index.css'), 'utf8'),
  ]);
  const out = `${generatedBanner}\n${parts.join('\n')}`;
  await writeFile(path.join(widgetDir, 'public', 'index.css'), out);
};

// Only the BROWSER side of a widget is bundled here. The API side (the code the
// Homey widget runtime loads inside the app process) is deliberately NOT
// bundled any more: each widget's committed `api.js` is a thin hand-written
// shim that requires `./src/api`, compiled to `.homeybuild` by the root tsc
// build (`tsconfig.json` includes `widgets/*/src/api.ts`). Bundling used to
// inline a private copy of every transitive shared-domain helper into each
// widget — five copies of code the app process had already loaded once for
// `lib/**`, each held in the V8 heap as source string + compiled code, on a
// runtime with ~15 MB of RSS headroom. `scripts/check-homeybuild-requires.mjs`
// walks the packaged require graph in CI, so a shim import that would not
// resolve in the shipped layout fails the build, not the boot.
const buildWidget = async ({ name, sharedCss = [] }) => {
  const widgetDir = path.join(rootDir, 'widgets', name);
  const widgetSrcDir = path.join(widgetDir, 'src');

  await build({
    entryPoints: [path.join(widgetSrcDir, 'public', 'index.ts')],
    outfile: path.join(widgetDir, 'public', 'index.js'),
    bundle: true,
    format: 'iife',
    target: 'es2020',
    platform: 'browser',
    banner: { js: generatedBanner },
  });

  await buildWidgetCss(widgetDir, sharedCss);
};

await buildWidget({ name: 'plan_budget', sharedCss: [FRAME_CSS, CHART_CSS] });
await buildWidget({ name: 'headroom' });
await buildWidget({ name: 'smart_tasks', sharedCss: [FRAME_CSS] });
await buildWidget({ name: 'create_smart_task', sharedCss: [CREATE_FLOW_CSS] });
await buildWidget({ name: 'device', sharedCss: [CREATE_FLOW_CSS] });
await buildWidget({ name: 'starvation_rescue' });
await buildWidget({ name: 'price', sharedCss: [FRAME_CSS, CHART_CSS] });
